//! The payload types the client returns.
//!
//! Garmin's Personal API is not a strongly typed API: the same field turns up
//! under three different names depending on the endpoint. Every type here
//! therefore carries a `raw` map with the untouched payload, so nothing the
//! reference implementation could read is lost.
//!
//! The extraction rules mirror `backend/app/services/personal_sync.py`'s
//! `_canonical_from_detail` and `backend/app/api/auth.py`'s
//! `_athlete_from_personal` exactly, including their fallbacks and their
//! defaults. The golden fixture in `tests/fixtures/` is generated by calling
//! those Python functions, so a mismatch here is a real mismatch.

use chrono::{DateTime, NaiveDateTime, Utc};
use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};

/// The athlete's Garmin profile.
///
/// Garmin's profile payload carries a dozen display names for the same person.
/// The four the reference implementation reads are lifted out; everything else
/// stays in [`Profile::raw`].
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Profile {
    /// `displayName` — the name the athlete sees in Garmin Connect.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub display_name: Option<String>,
    /// `fullName`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub full_name: Option<String>,
    /// `userName`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub user_name: Option<String>,
    /// `name`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
    /// The rest of the payload, untouched.
    #[serde(flatten)]
    pub raw: Map<String, Value>,
}

impl Profile {
    /// Builds a profile from Garmin's raw payload.
    pub fn from_value(payload: &Value) -> Self {
        let mut raw = match payload {
            Value::Object(map) => map.clone(),
            _ => Map::new(),
        };
        let display_name = truthy(raw.get("displayName")).map(value_to_string);
        let full_name = truthy(raw.get("fullName")).map(value_to_string);
        let user_name = truthy(raw.get("userName")).map(value_to_string);
        let name = truthy(raw.get("name")).map(value_to_string);
        // The struct carries a field called `name`, so that one key is taken
        // out of the raw map; everything else stays.
        raw.remove("name");
        Self {
            display_name,
            full_name,
            user_name,
            name,
            raw,
        }
    }

    /// The athlete's display name, whichever field Garmin used.
    ///
    /// The order matches the reference implementation's
    /// `_athlete_from_personal`: `displayName`, `fullName`, `userName`, `name`.
    pub fn athlete_name(&self) -> Option<&str> {
        self.display_name
            .as_deref()
            .or(self.full_name.as_deref())
            .or(self.user_name.as_deref())
            .or(self.name.as_deref())
    }
}

/// One heart-rate zone.
///
/// The field names are the ones `fingerprint.zone_model` builds, so a zone
/// model read here is a zone model the reference reads back.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Zone {
    /// The zone number, 1-based.
    pub zone_no: i64,
    /// The zone's name. Garmin's own name is not read by the reference; a zone
    /// without a name is `Zone {n}`.
    pub name: String,
    /// The lower bound, in beats per minute.
    pub low_bpm: f64,
    /// The upper bound, in beats per minute. The top zone has none.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub high_bpm: Option<f64>,
    /// The zone's payload, minus the four fields above.
    #[serde(flatten)]
    pub raw: Map<String, Value>,
}

/// The athlete's heart-rate zone model.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct ZoneModel {
    /// The zones the reference would build from the payload.
    pub zones: Vec<Zone>,
    /// The payload, untouched.
    #[serde(default)]
    pub raw: Map<String, Value>,
}

impl ZoneModel {
    /// Builds a zone model from Garmin's raw payload.
    ///
    /// The reference reads the zones out of `zones` or `heartRateZones`, and
    /// out of a payload that is itself a list. Each row's bounds are
    /// `low_bpm`/`zoneLowBoundary` and `high_bpm`/`zoneHighBoundary`, its
    /// number is `zone_no`/`zoneNumber`, and its name is `name`. A row
    /// without a usable lower bound is dropped, and so is a row whose upper
    /// bound is not positive.
    ///
    /// The reference derives five zones from the athlete's maximum heart rate
    /// when the payload does not yield exactly five; that derivation belongs
    /// to `stride-core`, not here.
    pub fn from_value(payload: &Value) -> Self {
        let raw = match payload {
            Value::Object(map) => map.clone(),
            _ => Map::new(),
        };
        let rows = match payload {
            Value::Array(items) => Some(items.clone()),
            Value::Object(map) => {
                let zones = map.get("zones").filter(|value| !is_empty(value));
                let heart_rate = map.get("heartRateZones").filter(|value| !is_empty(value));
                zones.or(heart_rate).and_then(Value::as_array).cloned()
            }
            _ => None,
        };
        let zones = rows
            .unwrap_or_default()
            .iter()
            .enumerate()
            .filter_map(|(index, row)| zone_from_value(row, index))
            .collect();
        Self { zones, raw }
    }

    /// The five zones the reference would use, sorted by their lower bound.
    ///
    /// `None` means the payload did not yield five zones, and the caller has
    /// to derive them from the athlete's maximum heart rate.
    pub fn zone_model(&self) -> Option<Vec<&Zone>> {
        if self.zones.len() != 5 {
            return None;
        }
        let mut zones: Vec<&Zone> = self.zones.iter().collect();
        zones.sort_by(|left, right| {
            left.low_bpm
                .partial_cmp(&right.low_bpm)
                .unwrap_or(std::cmp::Ordering::Equal)
        });
        Some(zones)
    }
}

/// True for an empty array, an empty object or a null.
fn is_empty(value: &Value) -> bool {
    match value {
        Value::Array(items) => items.is_empty(),
        Value::Object(map) => map.is_empty(),
        Value::Null => true,
        _ => false,
    }
}

/// One activity, as it appears in the activity list.
///
/// The list endpoint carries only what the reference implementation reads from
/// a list item: the id, the name and the local start time. The numbers live
/// in the activity's detail, and the reference reads them from there — see
/// [`ActivityDetail`].
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ActivitySummary {
    /// Garmin's activity id. This is the `external_id` the app stores.
    pub external_id: String,
    /// The activity's name.
    pub name: String,
    /// The sport, when the list item named one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sport_type: Option<String>,
    /// The activity's local start time, as Garmin sent it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub start_time_local: Option<String>,
    /// The rest of the payload, untouched.
    #[serde(flatten)]
    pub raw: Map<String, Value>,
}

impl ActivitySummary {
    /// Builds a summary from one item of the activity list.
    pub fn from_value(payload: &Value) -> Option<Self> {
        let object = payload.as_object()?;
        let mut raw = object.clone();
        let external_id = truthy(raw.get("activityId")).map(value_to_string)?;
        let name = truthy(raw.get("activityName"))
            .map(value_to_string)
            .or_else(|| truthy(raw.get("name")).map(value_to_string))
            .unwrap_or_else(|| "Run".to_owned());
        let sport_type = truthy(raw.get("activityTypeDTO"))
            .and_then(Value::as_object)
            .and_then(|dto| truthy(dto.get("typeKey")))
            .and_then(Value::as_str)
            .map(str::to_owned);
        let start_time_local = truthy(raw.get("startTimeLocal"))
            .and_then(Value::as_str)
            .map(str::to_owned);
        // The raw map is what a caller hands back to the canonicaliser as the
        // list item, so it keeps the id, the name and the start time. Only
        // "name" is taken out, because the struct carries a field of that
        // name.
        raw.remove("name");
        Some(Self {
            external_id,
            name,
            sport_type,
            start_time_local,
            raw,
        })
    }
}

/// An activity, canonicalised the way the reference implementation
/// canonicalises it.
///
/// The field names, the fallbacks and the defaults are those of
/// `personal_sync._canonical_from_detail`, so the numbers this produces are
/// the numbers the Python reference produces for the same payload.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ActivityDetail {
    /// Garmin's activity id.
    pub external_id: String,
    /// The activity's name.
    pub name: String,
    /// The sport type key.
    pub sport_type: String,
    /// The activity's start time, ISO-8601 in UTC.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub start_time: Option<String>,
    /// The athlete-local date of the activity.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub local_date: Option<String>,
    /// The English weekday name.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub day_of_week: Option<String>,
    /// The distance, in metres.
    pub distance_m: f64,
    /// The moving time, in seconds.
    pub moving_time_s: f64,
    /// The elapsed time, in seconds.
    pub elapsed_time_s: f64,
    /// The accumulated elevation gain, in metres.
    pub elevation_gain_m: f64,
    /// The average heart rate.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub avg_hr: Option<f64>,
    /// The maximum heart rate.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_hr: Option<f64>,
    /// The minimum heart rate.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub min_hr: Option<f64>,
    /// The calories.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub calories: Option<f64>,
    /// The average running cadence.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub avg_cadence: Option<f64>,
    /// The maximum running cadence.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_cadence: Option<f64>,
    /// The average speed, in metres per second.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub avg_speed_ms: Option<f64>,
    /// The maximum speed, in metres per second.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_speed_ms: Option<f64>,
    /// The watch that recorded it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub device: Option<String>,
    /// The payload this was read from, untouched.
    #[serde(flatten)]
    pub raw: Map<String, Value>,
}

impl ActivityDetail {
    /// Canonicalises an activity the way the reference implementation does.
    ///
    /// `detail` is the activity's detail payload and `list_item` the item it
    /// appeared as in the activity list, which the reference uses as a
    /// fallback for the id, the name and the start time.
    pub fn from_value(detail: &Value, list_item: Option<&Value>) -> Option<Self> {
        let detail_map = detail.as_object()?;
        let list_map = list_item.and_then(Value::as_object);
        let summary = truthy(detail_map.get("summaryDTO"))
            .and_then(Value::as_object)
            .cloned()
            .unwrap_or_default();
        let metadata = truthy(detail_map.get("metadataDTO"))
            .and_then(Value::as_object)
            .cloned()
            .unwrap_or_default();
        let activity_type = truthy(detail_map.get("activityTypeDTO"))
            .and_then(Value::as_object)
            .and_then(|dto| truthy(dto.get("typeKey")))
            .and_then(Value::as_str)
            .unwrap_or("running")
            .to_owned();
        let name = truthy(detail_map.get("activityName"))
            .and_then(Value::as_str)
            .map(str::to_owned)
            .or_else(|| {
                list_map
                    .and_then(|item| truthy(item.get("activityName")))
                    .and_then(Value::as_str)
                    .map(str::to_owned)
            })
            .or_else(|| {
                list_map
                    .and_then(|item| truthy(item.get("name")))
                    .and_then(Value::as_str)
                    .map(str::to_owned)
            })
            .unwrap_or_else(|| "Run".to_owned());
        let external_id = truthy(detail_map.get("activityId"))
            .or_else(|| list_map.and_then(|item| truthy(item.get("activityId"))))
            .map(id_to_string)
            .unwrap_or_default();

        let start_raw = truthy(summary.get("startTimeLocal"))
            .and_then(Value::as_str)
            .map(str::to_owned)
            .or_else(|| {
                list_map
                    .and_then(|item| truthy(item.get("startTimeLocal")))
                    .and_then(Value::as_str)
                    .map(str::to_owned)
            });
        let start = start_raw.as_deref().and_then(parse_local_datetime);
        let start_time = start.map(|value| {
            // Python's `isoformat()` renders a UTC offset as "+00:00", never "Z".
            value.to_rfc3339_opts(chrono::SecondsFormat::AutoSi, false)
        });
        let local_date = start.map(|value| value.date_naive().to_string());
        let day_of_week = start.map(|value| value.format("%A").to_string());

        let distance_m = safe_float(summary.get("distance"), Some(0.0)).unwrap_or(0.0);
        let moving_time_s = safe_float(
            truthy(summary.get("movingDuration")).or_else(|| summary.get("duration")),
            Some(0.0),
        )
        .unwrap_or(0.0);
        let elapsed_time_s = safe_float(
            truthy(summary.get("elapsedDuration")).or_else(|| summary.get("duration")),
            Some(0.0),
        )
        .unwrap_or(0.0);
        let elevation_gain_m = safe_float(summary.get("elevationGain"), Some(0.0)).unwrap_or(0.0);

        Some(Self {
            external_id,
            name,
            sport_type: activity_type,
            start_time,
            local_date,
            day_of_week,
            distance_m,
            moving_time_s,
            elapsed_time_s,
            elevation_gain_m,
            avg_hr: safe_float(summary.get("averageHR"), None),
            max_hr: safe_float(summary.get("maxHR"), None),
            min_hr: safe_float(summary.get("minHR"), None),
            calories: safe_float(summary.get("calories"), None),
            avg_cadence: safe_float(summary.get("averageRunCadence"), None),
            max_cadence: safe_float(summary.get("maxRunCadence"), None),
            avg_speed_ms: safe_float(summary.get("averageSpeed"), None),
            max_speed_ms: safe_float(summary.get("maxSpeed"), None),
            device: device_name(&metadata),
            raw: detail_map.clone(),
        })
    }
}

/// The watch that recorded an activity, the way the reference reads it.
fn device_name(metadata: &Map<String, Value>) -> Option<String> {
    if let Some(sensors) = truthy(metadata.get("sensors")).and_then(Value::as_array) {
        if let Some(first) = sensors.first().and_then(Value::as_object) {
            let manufacturer = first
                .get("manufacturer")
                .and_then(Value::as_str)
                .unwrap_or("");
            let product = first.get("product").and_then(Value::as_str).unwrap_or("");
            if !manufacturer.is_empty() || !product.is_empty() {
                let joined = format!("{manufacturer} {product}").trim().to_owned();
                if !joined.is_empty() {
                    return Some(joined);
                }
            }
        }
    }
    metadata
        .get("manufacturer")
        .and_then(|value| truthy(Some(value)))
        .map(|value| match value {
            Value::String(text) => text.clone(),
            other => other.to_string(),
        })
}

/// Python's `safe_float`: the value as a float, or the default.
fn safe_float(value: Option<&Value>, default: Option<f64>) -> Option<f64> {
    match value {
        None | Some(Value::Null) => default,
        Some(Value::String(text)) if text.is_empty() => default,
        Some(Value::Bool(flag)) => Some(if *flag { 1.0 } else { 0.0 }),
        Some(Value::Number(number)) => number.as_f64().or(default),
        Some(Value::String(text)) => match text.trim().parse::<f64>() {
            Ok(parsed) if parsed.is_finite() => Some(parsed),
            _ => default,
        },
        Some(_) => default,
    }
}

/// Python's truthiness, for the `or` chains the reference uses.
fn truthy(value: Option<&Value>) -> Option<&Value> {
    match value {
        None | Some(Value::Null) => None,
        Some(Value::Bool(false)) => None,
        Some(Value::Number(number)) if number.as_f64() == Some(0.0) => None,
        Some(Value::String(text)) if text.is_empty() => None,
        Some(Value::Array(items)) if items.is_empty() => None,
        Some(Value::Object(map)) if map.is_empty() => None,
        other => other,
    }
}

/// The id as a string, the way the reference stores it.
fn id_to_string(value: &Value) -> String {
    match value {
        Value::String(text) => text.clone(),
        Value::Number(number) => number.to_string(),
        other => other.to_string(),
    }
}

/// Any value as a string.
fn value_to_string(value: &Value) -> String {
    match value {
        Value::String(text) => text.clone(),
        other => other.to_string(),
    }
}

/// Parses a local start time the way the reference's `_parse_dt` does.
///
/// The reference reads the local start time with three fixed formats and then
/// as an ISO-8601 string, and treats it as UTC when it carries no offset.
fn parse_local_datetime(text: &str) -> Option<DateTime<Utc>> {
    for format in [
        "%Y-%m-%dT%H:%M:%S%.f",
        "%Y-%m-%dT%H:%M:%S",
        "%Y-%m-%d %H:%M:%S",
    ] {
        if let Ok(naive) = NaiveDateTime::parse_from_str(text, format) {
            return Some(DateTime::from_naive_utc_and_offset(naive, Utc));
        }
    }
    let normalised = text.replace('Z', "+00:00");
    match DateTime::parse_from_rfc3339(&normalised) {
        Ok(parsed) => Some(parsed.with_timezone(&Utc)),
        Err(_) => None,
    }
}

/// One zone, the way the reference reads it.
fn zone_from_value(payload: &Value, index: usize) -> Option<Zone> {
    let mut raw = match payload {
        Value::Object(map) => map.clone(),
        _ => return None,
    };
    // `dict.get(key, default)` only falls back when the key is absent, so a
    // key that is present and null is a null.
    let low = if raw.contains_key("low_bpm") {
        raw.get("low_bpm")
    } else {
        raw.get("zoneLowBoundary")
    };
    let high = if raw.contains_key("high_bpm") {
        raw.get("high_bpm")
    } else {
        raw.get("zoneHighBoundary")
    };
    let low_bpm = number(low, false)?;
    let high_bpm = match high {
        None | Some(Value::Null) => None,
        other => Some(number(other, true)?),
    };
    let zone_no = if raw.contains_key("zone_no") {
        raw.get("zone_no")
    } else if raw.contains_key("zoneNumber") {
        raw.get("zoneNumber")
    } else {
        None
    }
    .and_then(Value::as_i64)
    .unwrap_or(index as i64 + 1);
    let name = raw
        .get("name")
        .filter(|value| match value {
            Value::Null => false,
            Value::String(text) => !text.is_empty(),
            _ => true,
        })
        .and_then(Value::as_str)
        .map(str::to_owned)
        .unwrap_or_else(|| format!("Zone {}", index + 1));

    raw.remove("zone_no");
    raw.remove("name");
    raw.remove("low_bpm");
    raw.remove("high_bpm");

    Some(Zone {
        zone_no,
        name,
        low_bpm,
        high_bpm,
        raw,
    })
}

/// The reference's `number`: a real number, finite, and not below zero.
fn number(value: Option<&Value>, positive: bool) -> Option<f64> {
    let number = match value? {
        Value::Number(number) => number.as_f64()?,
        _ => return None,
    };
    if !number.is_finite() {
        return None;
    }
    if positive {
        if number > 0.0 {
            Some(number)
        } else {
            None
        }
    } else if number >= 0.0 {
        Some(number)
    } else {
        None
    }
}
